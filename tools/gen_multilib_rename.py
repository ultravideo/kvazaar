#!/usr/bin/env python3
"""Generate src/multilib_rename.h from the symbols of a kvazaar library.

Kvazaar can contain an encoder for several bit depths in one library. The
lowest bit depth is compiled as usual, and the others are compiled with
src/multilib_rename.h force included, which renames every external symbol of
the library (kvz_foo becomes kvz_foo_10bit for 10-bit) so that the copies do
not collide.

The list of symbols is taken from a static library with a single bit depth,
so it has to be regenerated when external functions or variables are added
to or removed from the library. A missing symbol shows up as a "multiple
definition" error when the library is linked.

Usage:
    cmake -B build-symbols -DKVZ_BIT_DEPTHS=8 -DBUILD_SHARED_LIBS=OFF
    cmake --build build-symbols --target kvazaar
    tools/gen_multilib_rename.py build-symbols/libkvazaar.a

    # With autotools:
    ./configure --with-bit-depths=8 --disable-shared && make
    tools/gen_multilib_rename.py src/.libs/libkvazaar.a

Use --check to only check that the header is up to date.
"""

